import { test, expect } from '@playwright/test'
import { db, siapkan, masuk, buatAdmin, bukaMenu, SANDI } from './bantu'

const acak = () => Date.now().toString().slice(-8) + Math.floor(Math.random() * 90 + 10)
const nipAcak = () => `1987${acak()}0000`.slice(0, 18)
const nikAcak = () => `5201${acak()}00`.slice(0, 16)

test('admin menambah guru PNS: banner menampilkan NIP sebagai username dan sandi 8 angka yang bisa dipakai', async ({ page, context }) => {
  const admin = await buatAdmin()
  const nip = nipAcak()
  await masuk(page, admin.email)
  await expect(page).toHaveURL('/admin')
  await page.goto('/admin/guru')
  await page.getByRole('button', { name: 'Tambah guru' }).click()
  await expect(page.locator('dialog.modal-profil')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tambah guru' }).last()).toBeEnabled()

  await page.getByLabel('Nama lengkap').fill('Halimah, S.Ag.')
  await page.getByLabel('Status kepegawaian').selectOption('PNS')
  await page.getByLabel('NIP', { exact: true }).fill(nip)
  await page.getByLabel('Kepala sekolah').check()
  await page.getByLabel('Tahun sertifikasi').fill('2012')
  await page.locator('dialog.modal-profil button[type="submit"]').click()

  const banner = page.getByRole('status', { name: 'Akun berhasil dibuat' })
  await expect(banner.getByText('Guru berhasil ditambahkan.')).toBeVisible()
  await expect(banner.getByText('Username (NIP)')).toBeVisible()
  await expect(page.getByTestId('username-baru')).toHaveText(nip)
  const sandi = (await page.getByTestId('sandi-baru').innerText()).trim()
  expect(sandi).toMatch(/^\d{8}$/)
  expect(await db.guru.findUniqueOrThrow({ where: { username: nip } })).toMatchObject({ jabatan: 'KEPSEK', disetujui: true, tahunSertifikasi: 2012 })

  await context.clearCookies()
  await masuk(page, nip, sandi)
  await expect(page).toHaveURL('/dokumen')
})

